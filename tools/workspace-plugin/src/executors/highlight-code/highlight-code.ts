import { logger, type PromiseExecutor } from '@nx/devkit';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join } from 'node:path';
import { createHighlighter, type ThemeRegistration } from 'shiki';
import type { HighlightCodeExecutorSchema } from './schema';

/** The languages a sample can be written in, by file extension. */
export const LANGUAGES = {
  '.sh': { name: 'curl', grammar: 'shellscript' },
  '.js': { name: 'node', grammar: 'javascript' },
  '.py': { name: 'python', grammar: 'python' },
  '.php': { name: 'php', grammar: 'php' },
  '.go': { name: 'go', grammar: 'go' },
} as const;

type Extension = keyof typeof LANGUAGES;

/**
 * The classes a token can take. Shiki colours each token from a theme, so a
 * theme whose every colour stands for one class tells us the class back.
 */
const CLASSES = {
  '#000001': 'k', // keywords and storage
  '#000002': 's', // strings
  '#000003': 'c', // comments
  '#000004': 'n', // numbers and constants
  '#000005': 'f', // function names
} as const;

const PLAIN = '#000000';

const SENTINEL_THEME: ThemeRegistration = {
  name: 'motifs-sentinel',
  type: 'dark',
  settings: [
    { settings: { foreground: PLAIN } },
    {
      scope: ['keyword', 'storage', 'keyword.operator.new'],
      settings: { foreground: '#000001' },
    },
    { scope: ['string', 'string.quoted'], settings: { foreground: '#000002' } },
    {
      scope: ['comment', 'punctuation.definition.comment'],
      settings: { foreground: '#000003' },
    },
    {
      scope: ['constant.numeric', 'constant.language', 'constant.other'],
      settings: { foreground: '#000004' },
    },
    {
      scope: ['entity.name.function', 'support.function'],
      settings: { foreground: '#000005' },
    },
  ],
};

/** A line of code: plain text as a string, a styled token as `[class, text]`. */
export type Line = (string | readonly [string, string])[];

const TASK = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/**
 * Highlights every sample in `input` with Shiki and writes their token
 * lines to `output`. The page renders the tokens itself, so it ships no
 * highlighter and needs no `innerHTML`.
 */
const runExecutor: PromiseExecutor<HighlightCodeExecutorSchema> = async (
  { input, output },
  context,
) => {
  try {
    const source = join(context.root, input);
    const files = readdirSync(source)
      .filter((file) => extname(file) in LANGUAGES)
      .sort();
    const highlighter = await createHighlighter({
      themes: [SENTINEL_THEME],
      langs: Object.values(LANGUAGES).map((language) => language.grammar),
    });

    const samples: Record<string, Record<string, Line[]>> = {};
    for (const file of files) {
      const extension = extname(file) as Extension;
      const task = basename(file, extension);
      if (!TASK.test(task)) {
        throw new Error(
          `${file}: name samples <task>.<extension>, in lowercase words joined by hyphens.`,
        );
      }
      const code = readFileSync(join(source, file), 'utf-8').replace(
        /\n+$/,
        '',
      );
      const { tokens } = highlighter.codeToTokens(code, {
        lang: LANGUAGES[extension].grammar,
        theme: 'motifs-sentinel',
      });
      samples[task] ??= {};
      (samples[task] as Record<string, Line[]>)[LANGUAGES[extension].name] =
        tokens.map((line) =>
          mergeLine(
            line.map((token) => [classOf(token.color), token.content] as const),
          ),
        );
    }
    highlighter.dispose();

    mkdirSync(dirname(join(context.root, output)), { recursive: true });
    writeFileSync(join(context.root, output), outputSource(samples));
    logger.info(`Highlighted ${files.length} sample(s) into ${output}.`);
    return { success: true };
  } catch (error) {
    logger.error(error instanceof Error ? error.message : String(error));
    return { success: false };
  }
};

function classOf(color: string | undefined): string {
  const key = (color ?? PLAIN).toLowerCase().slice(0, 7);
  return key in CLASSES ? CLASSES[key as keyof typeof CLASSES] : '';
}

/** Joins neighbouring tokens of one class, and writes plain ones as strings. */
export function mergeLine(
  tokens: readonly (readonly [string, string])[],
): Line {
  const merged: [string, string][] = [];
  for (const [cls, text] of tokens) {
    const last = merged[merged.length - 1];
    if (last && (last[0] === cls || text.trim() === '')) {
      last[1] += text;
    } else {
      merged.push([cls, text]);
    }
  }
  return merged.map(([cls, text]) => (cls ? ([cls, text] as const) : text));
}

/** The generated file, as TypeScript the app imports. */
export function outputSource(
  samples: Record<string, Record<string, Line[]>>,
): string {
  return [
    '// Generated by the highlight-code executor from the sample files.',
    "// Do not edit: run the app's highlight target instead.",
    '',
    '/** A line of code: plain text as a string, a styled token as [class, text]. */',
    'export type Line = readonly (string | readonly [string, string])[];',
    '',
    'export const SAMPLES: Readonly<',
    '  Record<string, Readonly<Record<string, readonly Line[]>>>',
    `> = ${JSON.stringify(samples)};`,
    '',
  ].join('\n');
}

export default runExecutor;
